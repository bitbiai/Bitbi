import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { knowledgeVersion, knowledgeVersionInput, publicPageIds, publicContextForPath, getSuggestions, retrieveKnowledge } from '../workers/shared/website-assistant-knowledge.mjs';
import { knowledgeArticles } from '../workers/shared/website-assistant-content.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
export function validateKnowledgeSources(provenance, readSource) {
  const failures = [];
  for (const source of provenance.sources) {
    const text = readSource(source.file);
    for (const fact of source.includes) if (!text.includes(fact)) failures.push(`${source.file}: reviewed public fact changed; review the related help article`);
  }
  return failures;
}
export const contentVersion = input => `kb1-${createHash('sha256').update(input).digest('hex').slice(0, 24)}`;

export function validatePublicArticles(articles) {
  const failures = [], seen = new Set();
  for (const article of articles) {
    if (!/^[a-z][a-z0-9-]{1,63}$/.test(article.id) || seen.has(article.id)) failures.push('Public knowledge article IDs must be unique and bounded.');
    seen.add(article.id);
    if (!Array.isArray(article.pages) || !article.pages.length || article.pages.some(page => !publicPageIds.includes(page))) failures.push(`${article.id}: invalid page context`);
    if (typeof article.path !== 'string' || !article.path.startsWith('/') || article.path.startsWith('//') || /[?\\%]/.test(article.path) || article.path.includes('..') || !publicContextForPath(article.path.split('#')[0])) failures.push(`${article.id}: invalid public source path`);
    for (const language of ['en', 'de']) for (const [field, max] of [['title', 120], ['question', 160], ['text', 3000]]) {
      const value = article[language]?.[field];
      if (typeof value !== 'string' || !value.trim() || value.length > max) failures.push(`${article.id}/${language}: invalid ${field}`);
    }
  }
  return failures;
}

export function checkWebsiteAssistantKnowledge({ refresh = false } = {}) {
  const provenance = JSON.parse(readFileSync(resolve(root, 'config/website-assistant-sources.json'), 'utf8'));
  const failures = [...validateKnowledgeSources(provenance, file => readFileSync(resolve(root, file), 'utf8')), ...validatePublicArticles(knowledgeArticles)];
  for (const pageId of publicPageIds) for (const language of ['en', 'de']) {
    const suggestions = getSuggestions({ pageId, language });
    if (suggestions.length !== 3 || new Set(suggestions.map(item => item.id)).size !== 3) failures.push(`${pageId}/${language}: three distinct supported questions required`);
    for (const suggestion of suggestions) {
      const found = retrieveKnowledge({ question: suggestion.question, pageId, language });
      if (!suggestion.sourceIds.every(id => found.some(doc => doc.id === id))) failures.push(`${pageId}/${language}/${suggestion.id}: answer not retrieved`);
    }
  }
  const expectedVersion = contentVersion(knowledgeVersionInput());
  if (refresh && !failures.length) {
    writeFileSync(resolve(root, 'workers/shared/website-assistant-version.mjs'), `// Generated by scripts/check-website-assistant-knowledge.mjs --refresh.\nexport const knowledgeVersion = '${expectedVersion}';\n`);
  } else if (knowledgeVersion !== expectedVersion) failures.push('Public content changed: review the articles, then run node scripts/check-website-assistant-knowledge.mjs --refresh.');
  if (failures.length) { console.error([...new Set(failures)].join('\n')); process.exitCode = 1; }
  else console.log(`Website assistant knowledge: ${expectedVersion}; ${publicPageIds.length * 2} page/language suggestion sets verified.`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) checkWebsiteAssistantKnowledge({ refresh: process.argv.includes('--refresh') });
