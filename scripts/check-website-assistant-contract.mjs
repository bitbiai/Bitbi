import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { assistantContractVersion } from '../workers/shared/website-assistant-contract-version.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const inputs = [
  'workers/shared/website-assistant-knowledge.mjs',
  'workers/auth/src/routes/website-assistant.js',
  'workers/auth/src/lib/website-assistant-policy.js',
  'workers/auth/src/lib/website-assistant-control.js',
  'workers/auth/src/lib/website-assistant-provider.js',
  'workers/auth/src/lib/website-assistant-budget.js',
  'workers/auth/src/lib/public-rate-limiter-do.js',
  'js/shared/website-assistant.js', 'js/shared/website-assistant-context.mjs',
  'js/shared/help-menu.js', 'js/shared/soft-nav.js', 'css/components/website-assistant.css',
];
const hash = createHash('sha256');
for (const file of inputs) hash.update(file + '\0').update(readFileSync(root + file)).update('\0');
const policy = JSON.parse(readFileSync(root + 'config/website-assistant.json', 'utf8'));
// Receipt itself is not an input to its content identity. Approval/rates/limits
// are: changing any of them requires renewed acceptance through existing release.
delete policy.acceptance;
hash.update(JSON.stringify(policy));
const version = 'wa1-' + hash.digest('hex').slice(0, 32);
if (process.argv.includes('--refresh')) {
  writeFileSync(root + 'workers/shared/website-assistant-contract-version.mjs',
    `// Generated by scripts/check-website-assistant-contract.mjs --refresh.\nexport const assistantContractVersion = '${version}';\n`);
} else if (assistantContractVersion !== version) {
  console.error('Website assistant inputs changed: review them, refresh the contract version; old real-provider acceptance cannot activate changed inputs.');
  process.exitCode = 1;
}
if (!process.exitCode) console.log(`Website assistant contract: ${version}; public ${policy.accessConfirmed ? 'access confirmed' : 'access unconfirmed'}.`);
